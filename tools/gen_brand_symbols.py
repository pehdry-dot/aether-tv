def read(path):
    root = ET.parse(path).getroot()
    vb = [float(v) for v in re.split(r"[\s,]+", root.attrib["viewBox"].strip())]
    paths = [e.attrib["d"].strip() for e in root.iter() if e.tag.endswith("path") and "d" in e.attrib]
    if not paths:
        sys.exit(f"no path in {path}")
    return vb, " ".join(paths)

def main(si_dir, cf_dir, out):
    lines = ["package com.aether.tv.core.designsystem", "",
             "// Generated by tools/gen_brand_symbols.py: do not edit. Provenance and licences: licenses/BRAND-SYMBOLS.md.",
             "// Brand marks identify their services; their owners keep their trademark rights. No endorsement is implied.", "",
             "internal object BrandSymbolData {",
             "    class Mark(val id: String, val title: String, val viewBox: FloatArray, val path: String, val source: String)", "",
             "    val marks: Map<String, Mark> = listOf("]
    pkgs = []
    for mid, (title, src, file, packages) in MARKS.items():
        d = si_dir if src == "si" else cf_dir
        vb, path = read(os.path.join(d, file + ".svg"))
        source = f"{SI}, icons/{file}.svg" if src == "si" else f"CleanFrame app/assets/icons/{file}.svg (see BRAND-SYMBOLS.md)"
        lines.append(f'        Mark("{mid}", "{title}", floatArrayOf({", ".join(f"{v:g}f" for v in vb)}), "{path}", "{source}"),')
        pkgs += [(p, mid) for p in packages]
    lines += ["    ).associateBy { it.id }", "",
              "    /** Installed packages these marks stand for. */",
              "    val byPackage: Map<String, String> = mapOf("]
    lines += [f'        "{p}" to "{m}",' for p, m in pkgs]
    lines += ["    )", "}", ""]
    open(out, "w").write("\n".join(lines))
    print(f"{len(MARKS)} marks, {len(pkgs)} packages -> {out}")

if __name__ == "__main__":
    main(*sys.argv[1:4])
